const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Allow plain HTTP to the local development backend only.
 *
 * Android 9+ blocks cleartext traffic by default, so a release APK talking to
 * `http://<laptop-ip>:8787` fails every request — and because parsing falls
 * back to manual entry (FR-10), it fails *silently*, looking like a broken
 * backend rather than a blocked connection.
 *
 * This permits cleartext for the dev host named in EXPO_PUBLIC_API_URL and
 * nothing else, so the NFR "HTTPS only" rule still holds for every other
 * destination. A deployed backend should be HTTPS and needs none of this.
 */
function devHost() {
  const url = process.env.EXPO_PUBLIC_API_URL;
  if (!url) return null;
  try {
    const { protocol, hostname } = new URL(url);
    return protocol === 'http:' ? hostname : null;
  } catch {
    return null;
  }
}

/** IPv4 literal, e.g. a laptop on the LAN. */
const isIpLiteral = (host) => /^\d{1,3}(\.\d{1,3}){3}$/.test(host);

/**
 * Android matches <domain> entries by HOSTNAME. An IP literal never matches
 * one, so a scoped domain-config silently falls through to base-config — and
 * a base-config of cleartextTrafficPermitted="false" then blocks every
 * request to a LAN IP at the platform layer, with no logcat entry and a
 * generic fetch failure in JS.
 *
 * So: scope by domain when the dev host is a name, and permit cleartext at
 * the base when it is a bare IP. Either way this file is only generated when
 * EXPO_PUBLIC_API_URL is plain http — point the app at an https backend and
 * no exemption is emitted at all.
 */
function configFor(host) {
  if (isIpLiteral(host)) {
    return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withDevCleartext.js from EXPO_PUBLIC_API_URL.
     DEV ONLY. ${host} is an IP literal, which Android cannot match with a
     <domain> rule, so cleartext is permitted at the base. Build against an
     https backend and this file is not generated. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true" />
</network-security-config>
`;
  }
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withDevCleartext.js from EXPO_PUBLIC_API_URL. -->
<network-security-config>
    <!-- Everything not listed below stays HTTPS-only. -->
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${host}</domain>
    </domain-config>
</network-security-config>
`;
}

module.exports = function withDevCleartext(config) {
  const host = devHost();
  if (!host) return config;

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), configFor(host));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
};
